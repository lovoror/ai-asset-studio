export const messages: Record<Lang, Partial<Dict>> = { en, zh };

/** Interpolation values. Nullish renders as an empty string, so a missing number never prints "null". */
export type Vars = Record<string, string | number | null | undefined>;

/** Translate a key for a given language, with {var} interpolation and `<key>_plural` when vars.n !== 1. */
export function translate(lang: Lang, key: string, vars?: Vars): string {
  let k = key;
  if (vars && typeof vars.n === "number" && vars.n !== 1) {
    const plural = key + "_plural";
    if (plural in en) k = plural;
  }
  const table = messages[lang] || en;
  let s = (table as Record<string, string>)[k] ?? (en as Record<string, string>)[k] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) s = s.split(`{${name}}`).join(value == null ? "" : String(value));
  }
  return s;
}

/** `const t = useT(); t("create.title")` - re-renders on language change because it subscribes to the store. */
export function useT() {
  const lang = useStore((s) => s.lang);
  return (key: string, vars?: Vars) => translate(lang, key, vars);
}

/** Turn the structured problems from /v1/readiness (or a refused submission) into localised sentences. */
export function useGate() {
  const t = useT();
  return (problems: { code?: string; role?: string; lane?: string; url?: string; missing?: string; detail?: string }[] = []) =>
    problems.map((p) => {
      if (p.code === "worker_unreachable") return t("gate.worker_unreachable", { role: t(`role.${p.role}`), url: p.url });
      if (p.code === "backend_unreachable") return t("gate.backend_unreachable", { lane: t(`lane.${p.lane}`), url: p.url });
      if (p.code === "backend_not_configured") return t("gate.backend_not_configured", { lane: t(`lane.${p.lane}`), missing: p.missing });
      return p.detail || p.code || "";
    });
}

/** Localised datetime helpers; `useT` owns the language so these re-render with it. */
export function useFmt() {
  const lang = useStore((s) => s.lang);
  return {
    ago: (ts: number) => {
      const d = Math.max(0, Date.now() / 1000 - ts);
      if (d < 60) return translate(lang, "time.justNow");
      if (d < 3600) return translate(lang, "time.minAgo", { n: Math.floor(d / 60) });
      if (d < 86400) return translate(lang, "time.hAgo", { n: Math.floor(d / 3600) });
      return new Date(ts * 1000).toLocaleDateString(lang === "zh" ? "zh-CN" : "en-GB");
    },
    dur: (s?: number | null) => {
      if (s == null) return "–";
      if (s < 90) return translate(lang, "time.seconds", { n: Math.round(s) });
      const m = Math.floor(s / 60);
      return translate(lang, "time.minutesSeconds", { m, s: Math.round(s - m * 60) });
    },
    /** Stage name -> localised label. Unknown stages fall through to their raw id. */
    stage: (name: string) => {
      const key = `stage.${name}`;
      return key in en ? translate(lang, key) : name;
    },
    /** Short status chip text. */
    status: (s: string) => {
      const key = `status.${s}`;
      return key in en ? translate(lang, key) : s;
    },
  };
}
